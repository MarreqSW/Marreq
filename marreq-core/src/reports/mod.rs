//! Report documents with configurable sections (issue #354): a template
//! ([`definition::ReportDefinition`]) chooses the sections, their order and
//! options; [`sections`] turns project data into a format-neutral
//! [`model::Document`]; [`pdf`] (Typst) and [`odt`] write it out.

pub mod data;
pub mod definition;
pub mod model;
pub mod odt;
pub mod pdf;
pub mod sections;

use serde::{Deserialize, Serialize};

use crate::app::{AppState, DieselCachedRepo};
use crate::repository::errors::RepoError;
