#!/usr/bin/env python3
"""Reproduce TypeScript wire types and compiled-Rocket route expectations."""
import argparse
import json
import sys

from compatibility import ROOT, load


def ts(node):
    if node is True or node == {}:
        return "unknown"
    if node is False:
        return "never"
    if "$ref" in node:
        return node["$ref"].split("/")[-1]
    for key in ("oneOf", "anyOf", "allOf"):
        if key in node:
            join = " & " if key == "allOf" else " | "
            return "(" + join.join(ts(item) for item in node[key]) + ")"
    if "const" in node:
        return json.dumps(node["const"])
    if "enum" in node:
        return " | ".join(json.dumps(item) for item in node["enum"])
    kind = node.get("type")
    if isinstance(kind, list):
        return " | ".join(ts({**node, "type": value}) for value in kind)
    if kind == "null":
        return "null"
    if kind in ("number", "integer"):
        return "number"
    if kind in ("string", "boolean"):
        return kind
    if kind == "array":
        return f"Array<{ts(node.get('items', {}))}>"
    if kind == "object" or "properties" in node:
        lines = []
        for name, value in node.get("properties", {}).items():
            optional = "" if name in node.get("required", []) else "?"
            lines.append(f"  {json.dumps(name)}{optional}: {ts(value)};")
        extra = node.get("additionalProperties", True)
        if isinstance(extra, dict):
            lines.append(f"  [key: string]: {ts(extra)};")
        elif extra:
            lines.append("  [key: string]: unknown;")
        return "{\n" + "\n".join(lines) + "\n}"
    if node.get("x-marreq-unverified"):
        return "unknown"
    raise ValueError(f"unsupported TypeScript schema: {node}")


def generated(spec):
    header = "// Generated by scripts/contracts/generate.py from docs/developer/openapi.yaml.\n// Do not edit; this file carries wire types, not a second contract.\n\n"
    types = header + "\n\n".join(f"export type {name} = {ts(schema)};" for name, schema in sorted(spec["components"]["schemas"].items())) + "\n"
    routes = []
    for path, item in spec["paths"].items():
        for method, operation in item.items():
            routes.append({"method": method.upper(), "path": path, "variants": operation.get("x-marreq-variants", ["server", "cloud"])})
    return {
        ROOT / "frontend/src/api/generated-contract.ts": types,
        ROOT / "mcp-server/src/generated-contract.ts": types,
        ROOT / "docs/developer/api-contract-routes.json": json.dumps(routes, indent=2) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in generated(load(ROOT / "docs/developer/openapi.yaml")).items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if stale:
        print("Generated contract drift; run python3 scripts/contracts/generate.py:\n" + "\n".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
