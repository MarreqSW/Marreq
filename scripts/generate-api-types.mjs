// Standard OpenAPI -> TypeScript generation; only component-reachable schemas.
// Committed declarations keep Rust/global OpenAPI out of consumer Docker builds.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync, rmSync, readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import ts from 'typescript';

// Derive type roots from imports, rather than maintaining another schema list.
function schemaReferences(node, aliases) {
  const roots = new Set();
  function visit(node) {
    if (ts.isIndexedAccessTypeNode(node) && ts.isIndexedAccessTypeNode(node.objectType)) {
      const inner = node.objectType;
      if (ts.isTypeReferenceNode(inner.objectType) && ts.isIdentifier(inner.objectType.typeName) &&
          aliases.has(inner.objectType.typeName.text) &&
          ts.isLiteralTypeNode(inner.indexType) && inner.indexType.literal.text === 'schemas') {
        if (!ts.isLiteralTypeNode(node.indexType) || !ts.isStringLiteral(node.indexType.literal)) {
          throw new Error('Generated schemas require a literal type association');
        }
        roots.add(node.indexType.literal.text);
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(node);
  return roots;
}

function usedSchemas(directory) {
  const roots = new Set();
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      if (entry.name !== '__tests__') for (const name of usedSchemas(path)) roots.add(name);
      continue;
    }
    if (!/\.tsx?$/.test(entry.name) || /(?:\.test\.tsx?|generated-contract\.ts)$/.test(entry.name)) continue;
    const source = ts.createSourceFile(path, readFileSync(path, 'utf8'), ts.ScriptTarget.Latest, true);
    const aliases = new Set();
    for (const statement of source.statements) {
      if (!ts.isImportDeclaration(statement) || !/generated-contract(?:\.js)?$/.test(statement.moduleSpecifier.text)) continue;
      const bindings = statement.importClause?.namedBindings;
      if (bindings && ts.isNamedImports(bindings)) {
        for (const binding of bindings.elements) {
          if ((binding.propertyName ?? binding.name).text === 'components') aliases.add(binding.name.text);
        }
      }
    }
    for (const name of schemaReferences(source, aliases)) roots.add(name);
  }
  return roots;
}

function selectTypes(ast, roots) {
  const declaration = ast.find(node => node.name?.escapedText === 'components');
  const schemas = declaration.members.find(node => node.name?.text === 'schemas');
  const available = new Map(schemas.type.members.map(node => [node.name.text, node]));
  const selected = new Set();
  for (const name of roots) {
    if (selected.has(name)) continue;
    const node = available.get(name);
    if (!node) throw new Error(`Consumer imports schema outside its HTTP contract: ${name}`);
    selected.add(name);
    for (const dependency of schemaReferences(node, new Set(['components']))) roots.add(dependency);
  }
  const members = [...selected].sort().map(name => available.get(name));
  const pruned = ts.factory.updatePropertySignature(schemas, schemas.modifiers, schemas.name, schemas.questionToken,
    ts.factory.createTypeLiteralNode(members));
  return [ts.factory.updateInterfaceDeclaration(declaration, declaration.modifiers, declaration.name,
    declaration.typeParameters, declaration.heritageClauses, [pruned])];
}
const check = process.argv.includes('--check');
const directory = mkdtempSync(join(tmpdir(), 'marreq-types-'));
try {
  for (const component of ['frontend', 'mcp']) {
    const path = join(directory, `${component}.json`);
    execFileSync('cargo', ['run', '--quiet', '--locked', '-p', 'marreq-contracts', '--', 'select', '--component', component, '--output', path]);
    const spec = JSON.parse(readFileSync(path, 'utf8'));
    spec.paths = {}; // Clients currently import schemas, not generated SDK paths.
    const ast = await openapiTS(spec, { alphabetize: true });
    const declarations = selectTypes(ast, usedSchemas(component === 'frontend' ? 'frontend/src' : 'mcp-server/src'));
    const result = '// Generated by scripts/generate-api-types.mjs; do not edit.\n' + astToString(declarations);
    const output = component === 'frontend' ? 'frontend/src/api/generated-contract.ts' : 'mcp-server/src/generated-contract.ts';
    if (check) {
      if (readFileSync(output, 'utf8') !== result) throw new Error(`${output}: generated type drift; run node scripts/generate-api-types.mjs`);
    } else writeFileSync(output, result);
  }
} finally { rmSync(directory, { recursive: true, force: true }); }
