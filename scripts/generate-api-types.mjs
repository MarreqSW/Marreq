// Standard OpenAPI -> TypeScript generation; only component-reachable schemas.
// Committed declarations keep Rust/global OpenAPI out of consumer Docker builds.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
const check = process.argv.includes('--check');
const directory = mkdtempSync(join(tmpdir(), 'marreq-types-'));
try {
  for (const component of ['frontend', 'mcp']) {
    const path = join(directory, `${component}.json`);
    // Inventory-only entries generate no invented types. Strict release/CI
    // coverage is checked separately by `marreq-contracts validate --consumers`.
    execFileSync('cargo', ['run', '--quiet', '--locked', '-p', 'marreq-contracts', '--', 'select', '--component', component, '--allow-unverified', '--output', path]);
    const spec = JSON.parse(readFileSync(path, 'utf8'));
    spec.paths = {}; // Clients currently import schemas, not generated SDK paths.
    const ast = await openapiTS(spec);
    const declarations = ast.filter(node => node.name?.escapedText === 'components');
    const result = '// Generated by scripts/generate-api-types.mjs; do not edit.\n' + astToString(declarations);
    const output = component === 'frontend' ? 'frontend/src/api/generated-contract.ts' : 'mcp-server/src/generated-contract.ts';
    if (check) {
      if (readFileSync(output, 'utf8') !== result) throw new Error(`${output}: generated type drift; run node scripts/generate-api-types.mjs`);
    } else writeFileSync(output, result);
  }
} finally { rmSync(directory, { recursive: true, force: true }); }
